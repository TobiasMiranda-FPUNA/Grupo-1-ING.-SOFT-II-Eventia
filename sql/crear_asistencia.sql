-- ============================================================
-- crear_asistencia.sql
-- Proyecto: Eventia - Sistema de Gestión de Eventos
-- Motor: PostgreSQL
--
-- Dependencias:
--   INSCRIPCION
--   ACTIVIDAD
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS asistencia (
    id_asistencia          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscripcion         BIGINT      NOT NULL,
    id_actividad           BIGINT      NOT NULL,
    fecha_hora_registro    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado                 VARCHAR(20) NOT NULL DEFAULT 'presente',
    creado_en              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_asistencia_inscripcion_actividad
        UNIQUE (id_inscripcion, id_actividad),

    CONSTRAINT fk_asistencia_inscripcion
        FOREIGN KEY (id_inscripcion)
        REFERENCES inscripcion (id_inscripcion)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_asistencia_actividad
        FOREIGN KEY (id_actividad)
        REFERENCES actividad (id_actividad)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_asistencia_estado_valido
        CHECK (estado IN ('presente', 'ausente'))
);

-- Compatibilidad con bases creadas con una versión anterior del script.
ALTER TABLE asistencia
    DROP CONSTRAINT IF EXISTS ck_asistencia_estado_no_vacio;

ALTER TABLE asistencia
    DROP CONSTRAINT IF EXISTS ck_asistencia_estado_valido;

ALTER TABLE asistencia
    ADD CONSTRAINT ck_asistencia_estado_valido
    CHECK (estado IN ('presente', 'ausente'));

COMMENT ON TABLE asistencia IS
'Registra la asistencia de una inscripción a una actividad del evento.';

COMMENT ON CONSTRAINT uq_asistencia_inscripcion_actividad ON asistencia IS
'Impide registrar más de una asistencia para la misma inscripción y actividad.';

CREATE INDEX IF NOT EXISTS idx_asistencia_id_inscripcion
    ON asistencia (id_inscripcion);

CREATE INDEX IF NOT EXISTS idx_asistencia_id_actividad
    ON asistencia (id_actividad);

-- Acelera los conteos de presentes/ausentes por actividad (métricas).
CREATE INDEX IF NOT EXISTS idx_asistencia_actividad_estado
    ON asistencia (id_actividad, estado);

COMMIT;
