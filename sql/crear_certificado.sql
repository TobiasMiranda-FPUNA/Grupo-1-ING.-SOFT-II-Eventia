-- ============================================================
-- crear_certificado.sql
-- Proyecto: Eventia - Sistema de Gestión de Eventos
-- Motor: PostgreSQL
--
-- Dependencia:
--   INSCRIPCION
--
-- El código de validación se genera automáticamente en PostgreSQL
-- mediante gen_random_uuid(), se normaliza a 32 caracteres y además
-- queda protegido por una restricción UNIQUE.
-- ============================================================

BEGIN;

CREATE OR REPLACE FUNCTION generar_codigo_validacion_certificado()
RETURNS VARCHAR(32)
LANGUAGE SQL
VOLATILE
AS $$
    SELECT UPPER(REPLACE(gen_random_uuid()::TEXT, '-', ''));
$$;

CREATE TABLE IF NOT EXISTS certificado (
    id_certificado       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscripcion       BIGINT      NOT NULL,
    tipo                 VARCHAR(50) NOT NULL DEFAULT 'participacion',
    fecha_emision        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    codigo_validacion    VARCHAR(32) NOT NULL DEFAULT generar_codigo_validacion_certificado(),
    creado_en            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_certificado_inscripcion
        UNIQUE (id_inscripcion),

    CONSTRAINT uq_certificado_codigo_validacion
        UNIQUE (codigo_validacion),

    CONSTRAINT fk_certificado_inscripcion
        FOREIGN KEY (id_inscripcion)
        REFERENCES inscripcion (id_inscripcion)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_certificado_tipo_no_vacio
        CHECK (BTRIM(tipo) <> ''),

    CONSTRAINT ck_certificado_codigo_no_vacio
        CHECK (BTRIM(codigo_validacion) <> '')
);

COMMENT ON TABLE certificado IS
'Registra certificados emitidos para inscripciones y su código público de validación.';

COMMENT ON COLUMN certificado.codigo_validacion IS
'Código único generado por PostgreSQL para verificar públicamente la autenticidad del certificado.';

CREATE INDEX IF NOT EXISTS idx_certificado_codigo_validacion
    ON certificado (codigo_validacion);

COMMIT;
